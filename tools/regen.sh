#!/usr/bin/env bash
# regen.sh — regenerate the FoMT native build from the user's ROM.
# Adapted from Gitsnup/warioland4-recomp tools/regen.sh (5 steps).
# The ROM is the user's own dump; it is hash-gated, never shipped, and
# generated C++ is never committed (it is ROM-derived).
# Usage: tools/regen.sh --rom <path/to/fomt_usa.gba> [--jobs N] [--skip-decomp]
#
# Runs on Windows under MSYS2 (devkitPro pacman) or Linux/WSL.
# The decomp build (step 3) needs devkitARM (arm-none-eabi-*) plus
# notyourav/agbcc branch `cp`, installed by
# third_party/fomt/tools/install_agbcp.sh. If any of that is missing,
# step 3 degrades to finder-only mode and the pipeline continues —
# the decomp is optional, not a gate (Mega Man Zero precedent).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
JOBS="$(nproc 2>/dev/null || echo 4)"
SKIP_DECOMP=0
ROM=""

while [ $# -gt 0 ]; do
  case "$1" in
    --rom) ROM="$2"; shift 2 ;;
    --jobs) JOBS="$2"; shift 2 ;;
    --skip-decomp) SKIP_DECOMP=1; shift ;;
    *) echo "Unknown arg: $1" >&2; exit 1 ;;
  esac
done

[ -n "$ROM" ] || { echo "Usage: $0 --rom <fomt_usa.gba> [--jobs N] [--skip-decomp]" >&2; exit 1; }
[ -f "$ROM" ] || { echo "ERROR: ROM not found: $ROM" >&2; exit 1; }

DECOMP="$ROOT/third_party/fomt"
ENGINE="$ROOT/gbarecomp"
SYMS="$ROOT/variants/fomt/symbols"
GEN="$ROOT/variants/fomt/generated"
GAME_TOML="$ROOT/variants/fomt/game.toml"
ELF="$DECOMP/fomt.elf"
MAP="$DECOMP/fomt.map"
RECOMPILER="$ENGINE/build/gba_recompile"

# FoMT (USA) identity — SHA-1 per StanHash/fomt fomt.sha1 (verified
# 2026-11-21: Ray's dump matches exactly). md5/crc32 are computed from
# the ROM in step 1; fomt.sha1 carries only the SHA-1.
ROM_SHA1="a2fc3574f0a65a4fcf7682fb274b9d7eebdef963"

# Tool checks — fail fast with a useful message, before any long step.
for tool in sha1sum md5sum python3 cmake git; do
  command -v "$tool" >/dev/null 2>&1 || {
    echo "ERROR: required tool '$tool' not found on PATH." >&2
    echo "On Windows, run this from the MSYS2 shell (devkitPro pacman):" >&2
    echo "  pacman -S base-devel git python cmake" >&2
    exit 1
  }
done

log() { printf '\n=== %s ===\n' "$*"; }

# --- Step 1: ROM identity gate -------------------------------------------
log "1/5 ROM identity"
ACTUAL_SHA1="$(sha1sum "$ROM" | cut -d' ' -f1)"
[ "$ACTUAL_SHA1" = "$ROM_SHA1" ] || {
  echo "ERROR: ROM SHA-1 mismatch: got $ACTUAL_SHA1, want $ROM_SHA1" >&2
  echo "Refusing to continue. Supply your own US dump (see README.md)." >&2
  exit 1
}
ROM_MD5="$(md5sum "$ROM" | cut -d' ' -f1)"
ROM_CRC32="$(python3 - "$ROM" <<'PY'
import sys, zlib
crc = 0
with open(sys.argv[1], 'rb') as f:
    while True:
        b = f.read(1 << 20)
        if not b: break
        crc = zlib.crc32(b, crc)
print(f"0x{crc:08X}")
PY
)"
echo "ROM SHA-1 OK: $ROM_SHA1"
echo "ROM md5=$ROM_MD5 crc32=$ROM_CRC32"

# --- Step 2: stamp runtime configs ----------------------------------------
log "2/5 Stamping ROM identity into configs"
# md5 into variants/fomt/game.toml [identity]. Idempotent: matches the
# commented placeholder on the first run and the stamped value after.
sed -i -E "s|^(# )?md5 = .*|md5  = \"$ROM_MD5\"|" "$GAME_TOML"
grep -q "md5  = \"$ROM_MD5\"" "$GAME_TOML" || {
  echo "ERROR: could not stamp md5 into $GAME_TOML" >&2; exit 1; }
echo "  stamped $GAME_TOML"
# Identity header for the future desktop/Android shell (WL4 pattern).
# android/game_android.toml + android/app/build.gradle do not exist
# yet; their stamping lands with the Android packaging work.
mkdir -p "$ROOT/src"
cat > "$ROOT/src/fomt_rom_identity.h" <<EOF
// fomt_rom_identity.h — GENERATED by tools/regen.sh. Do not edit.
#pragma once
#define FOMT_ROM_SHA1 "$ROM_SHA1"
#define FOMT_ROM_CRC32 ${ROM_CRC32}u
EOF
echo "  generated src/fomt_rom_identity.h"

# --- Step 3: build the decomp (agbcc) -------------------------------------
# A failure here does NOT block the port — it means finder-only mode
# (no symbol import). The pipeline continues; pass --skip-decomp to
# skip this step outright. `make compare` both builds fomt.gba from
# fomt.elf and SHA-1-checks it against fomt.sha1 (it is the Makefile's
# default goal). NOTE: fomt's Makefile has no `make tools` /
# `make extract` targets (unlike WL4's decomp) — do not add them.
log "3/5 Decomp build (skip with --skip-decomp)"
DECOMP_OK=0
if [ "$SKIP_DECOMP" -eq 1 ]; then
  echo "  --skip-decomp: decomp build skipped (finder-only mode)."
elif ! command -v arm-none-eabi-gcc >/dev/null 2>&1 && [ -z "${DEVKITARM:-}" ]; then
  echo "  WARNING: no arm-none-eabi toolchain found (DEVKITARM unset," >&2
  echo "  arm-none-eabi-gcc not on PATH). Skipping decomp — finder-only mode." >&2
elif [ ! -d "$DECOMP" ]; then
  echo "  WARNING: decomp not found at $DECOMP — run tools/fetch-upstream.sh first." >&2
  echo "  Continuing finder-only." >&2
else
  # agbcc (notyourav fork, branch cp) via the decomp's own installer.
  if [ ! -x "$DECOMP/tools/agbcc/bin/agbcc" ]; then
    echo "  agbcc not installed — running third_party/fomt/tools/install_agbcp.sh ..."
    if ! (cd "$DECOMP" && ./tools/install_agbcp.sh); then
      echo "  WARNING: agbcc install failed. Continuing finder-only." >&2
    fi
  fi
  if [ -x "$DECOMP/tools/agbcc/bin/agbcc" ]; then
    cp "$ROM" "$DECOMP/baserom.gba"
    if make -C "$DECOMP" -j"$JOBS" compare; then
      echo "  decomp build OK: rebuilt ROM matches retail (sha1)."
      DECOMP_OK=1
    else
      echo "  WARNING: decomp build or 'make compare' failed — the decomp" >&2
      echo "  does not (yet) reproduce the retail ROM byte-for-byte." >&2
      echo "  Continuing finder-only (no symbol import)." >&2
    fi
  fi
fi

# --- Step 4: symbol import (only if step 3 passed) ------------------------
log "4/5 Symbol import"
SYMS_OK=0
if [ "$DECOMP_OK" -eq 0 ]; then
  echo "  Finder-only mode: no decomp symbols to import."
elif ! command -v arm-none-eabi-readelf >/dev/null 2>&1; then
  echo "  WARNING: arm-none-eabi-readelf not found — cannot import symbols." >&2
  echo "  Continuing finder-only." >&2
elif [ ! -f "$ELF" ] || [ ! -f "$MAP" ]; then
  echo "  WARNING: decomp ELF/MAP missing ($ELF / $MAP) — cannot import symbols." >&2
  echo "  Continuing finder-only." >&2
else
  mkdir -p "$SYMS"
  arm-none-eabi-readelf -sW "$ELF" > "$SYMS/FOMT_readelf_syms.txt"
  arm-none-eabi-readelf -SW "$ELF" > "$SYMS/FOMT_readelf_sections.txt"
  # --map points at the decomp's own fomt.map (not copied: *.map is
  # gitignored, and the importer only reads it).
  if python3 "$ENGINE/tools/symbol_import/import_decomp_symbols.py" \
      --id FOMT --name "Harvest Moon: Friends of Mineral Town (USA)" \
      --syms "$SYMS/FOMT_readelf_syms.txt" \
      --sections "$SYMS/FOMT_readelf_sections.txt" \
      --map "$MAP" \
      --rom "$ROM" \
      --out "$SYMS" \
    && [ -f "$SYMS/imported_symbols.tsv" ] \
    && [ -f "$SYMS/FOMT_symbols.toml" ]; then
    echo "  imported symbols in $SYMS"
    SYMS_OK=1
  else
    echo "  WARNING: symbol import failed or produced no output." >&2
    echo "  Continuing finder-only." >&2
  fi
fi

# --- Step 5: gba_recompile -------------------------------------------------
log "5/5 gba_recompile"
if [ ! -x "$RECOMPILER" ]; then
  cmake -S "$ENGINE" -B "$ENGINE/build" -DCMAKE_BUILD_TYPE=Release
  cmake --build "$ENGINE/build" --target gba_recompile -j"$JOBS"
fi
mkdir -p "$GEN"
RECOMPILE_ARGS=(
  --rom "$ROM"
  --config "$GAME_TOML"
)
if [ "$SYMS_OK" -eq 1 ]; then
  RECOMPILE_ARGS+=(
    --config "$SYMS/FOMT_symbols.toml"
    --symbols "$SYMS/imported_symbols.tsv"
  )
  # --data-symbols only when the importer actually emitted data symbols.
  if [ -f "$SYMS/imported_data_symbols.tsv" ]; then
    RECOMPILE_ARGS+=( --data-symbols "$SYMS/imported_data_symbols.tsv" )
  fi
else
  echo "  finder-only: no --symbols/--data-symbols (decomp symbols unavailable)."
fi
"$RECOMPILER" "${RECOMPILE_ARGS[@]}" --out "$GEN"

cat <<DONE

Done. Generated code is in $GEN.
  $(ls "$GEN" | sed 's/^/  /')

What this run did and did not prove:
  - The ROM translated (finder-only, or with decomp symbols if step 3
    passed). Static coverage is NOT proven by this script.
  - The desktop shell (root CMakeLists.txt + src/main.cpp) is not in
    the repo yet — that is the next piece of work. Once it lands:
      cmake -S . -B build-desktop -DCMAKE_BUILD_TYPE=Release
      cmake --build build-desktop -j"$JOBS"
      GBARECOMP_STRICT_STATIC=1 ./build-desktop/FoMTRecomp --frames 3600
    and look for the exit report: COVERAGE: FULLY_STATIC (want) vs
    NOT_STATIC, plus any recomp_master_misses_<tag>.toml.frag proposal
    naming the missing PCs — those become the next [[extra_func]] /
    [[jump_table]] / [[data_range]] hints in variants/fomt/game.toml.
DONE
